#!/usr/bin/env python3
"""Regenerate STATUS.md from analysis/ + records/. Never edit STATUS.md by hand.

    python3 tools/status.py           write STATUS.md
    python3 tools/status.py --check   fail if records contradict analysis or STATUS.md is out of date
"""
import sys
from collections import Counter, defaultdict

from model import LADDER, ROOT, config, load


def bar(done, total, width=20):
    n = round(width * done / total) if total else 0
    return "█" * n + "░" * (width - n)


def render():
    out = ["# Status", "", "_Generated by `tools/status.py` from `analysis/` and `records/`. Do not edit._", ""]
    for b in config()["build"]:
        fns = load(b["id"])
        if not fns:
            out += [f"## {b['id']}", "", "Not analysed yet.", ""]
            continue
        c = Counter(f.status for f in fns.values())
        total = len(fns)
        out += [f"## {b['id']}", "", "| status | functions | reached |", "|---|---:|---|"]
        for i, s in enumerate(LADDER):
            reached = sum(c[t] for t in LADDER[i:])
            out.append(f"| {s} | {c[s]:,} | {bar(reached, total)} {reached / total:.1%} |")
        out += ["", f"{total:,} functions known. Reconstructed (decompiled or better): "
                    f"{sum(c[t] for t in LADDER[3:]):,}.", ""]
        subs = defaultdict(Counter)
        for f in fns.values():
            if not f.subsystem.startswith("_"):
                subs[f.subsystem][f.status] += 1
        if subs:
            out += ["### Identified functions by subsystem", "",
                    "| subsystem | named | decompiled+ | matches+ |", "|---|---:|---:|---:|"]
            for name, cc in sorted(subs.items(), key=lambda kv: (-sum(kv[1].values()), kv[0])):
                out.append(f"| `{name}` | {sum(cc.values()):,} | {sum(cc[t] for t in LADDER[3:]):,} | "
                           f"{sum(cc[t] for t in LADDER[5:]):,} |")
            out.append("")
    return "\n".join(out)


def main():
    try:
        text = render()
    except ValueError as e:
        sys.exit(f"records contradict analysis:\n{e}")
    path = ROOT / "STATUS.md"
    if "--check" in sys.argv:
        if not path.exists() or path.read_text() != text:
            sys.exit("STATUS.md is out of date: run python3 tools/status.py and commit the result")
        print("STATUS.md is current")
        return
    path.write_text(text)
    print(text[:1500])


if __name__ == "__main__":
    main()
